/**
 * discover command — Auto-extract rules from any codebase
 *
 * Scans the project's actual files to detect its technology stack and
 * propose rules. Works with any ecosystem: JS/TS, Python, Go, Rust,
 * Java/Kotlin, Swift, Ruby, Docker, Terraform, dbt, and more.
 *
 * Usage:
 *   harness-harness discover                    # Scan and show proposed rules
 *   harness-harness discover --write            # Write to repo rules (.harness/routes/)
 *   harness-harness discover --write --personal # Write to personal rules (.harness/local/routes/)
 *   harness-harness discover --write --org      # Write to org rules (~/.config/harness-harness/)
 */

import fs from 'fs';
import path from 'path';
import { resolvePaths } from '../lib/paths.js';
import { discoverRules, formatDiscoveredRules } from '../lib/rule-discovery.js';

export async function discover(projectDir, flags) {
  const paths = resolvePaths(projectDir);
  const writeMode = flags.includes('--write');
  const personal = flags.includes('--personal');
  const org = flags.includes('--org');

  console.log('');
  console.log('  Harness Harness — Discover Rules');
  console.log(`  Project: ${projectDir}`);
  console.log('');
  console.log('  Scanning...');

  const { rules, stack, fingerprint } = discoverRules(projectDir);

  console.log(`  Stack: ${fingerprint}`);
  console.log(`  Technologies detected: ${stack.length}`);
  console.log(`  Rules proposed: ${rules.length}`);
  console.log('');

  if (rules.length === 0) {
    console.log('  No conventions detected. Add a package.json, go.mod, Cargo.toml,');
    console.log('  pyproject.toml, Gemfile, or CLAUDE.md and try again.');
    return;
  }

  // Display rules grouped by confidence
  const high = rules.filter(r => r.confidence === 'high');
  const medium = rules.filter(r => r.confidence === 'medium');

  if (high.length > 0) {
    console.log('  Must Load (high confidence):');
    for (const r of high) {
      console.log(`    - ${r.rule}`);
      console.log(`      source: ${r.source}`);
    }
    console.log('');
  }

  if (medium.length > 0) {
    console.log('  Load If Budget Allows (medium confidence):');
    for (const r of medium) {
      console.log(`    - ${r.rule}`);
      console.log(`      source: ${r.source}`);
    }
    console.log('');
  }

  if (!writeMode) {
    console.log('  Preview only. To write rules:');
    console.log('    harness-harness discover --write              # repo rules (committed to git)');
    console.log('    harness-harness discover --write --personal   # personal rules (gitignored)');
    console.log('    harness-harness discover --write --org        # org rules (all repos on this machine)');
    console.log('');
    return;
  }

  // --- Write to org rules ---
  if (org) {
    const orgFile = paths.orgRulesFile;
    fs.mkdirSync(path.dirname(orgFile), { recursive: true });

    const lines = [
      '# Org Rules',
      `# Generated by harness-harness discover on ${new Date().toISOString().slice(0, 10)}`,
      '# These rules apply to ALL repos on this machine.',
      '# Edit freely. Re-run discover --write --org to regenerate.',
      '',
    ];
    for (const r of rules) {
      lines.push(`- ${r.rule}`);
    }
    lines.push('');
    fs.writeFileSync(orgFile, lines.join('\n'), 'utf8');
    console.log(`  Written: ${orgFile}`);
    console.log('  Layer: org (applies to all repos on this machine)');
    console.log(`  Rules written: ${rules.length}`);
    console.log('');
    return;
  }

  // --- Write to repo or personal routes ---
  const routeFilename = 'general.md'; // Use general.md as the default route
  const targetDir = personal ? paths.localRoutesDir : paths.routesDir;
  const targetFile = path.join(targetDir, routeFilename);

  fs.mkdirSync(targetDir, { recursive: true });

  if (fs.existsSync(targetFile)) {
    let content = fs.readFileSync(targetFile, 'utf8');
    const rulesMarkdown = formatDiscoveredRules(rules);

    const routeContextRe = /## Route Context\n[\s\S]*?(?=\n## |\n---|\s*$)/;
    if (routeContextRe.test(content)) {
      content = content.replace(routeContextRe, `## Route Context\n${rulesMarkdown}`);
    } else {
      content += `\n## Route Context\n${rulesMarkdown}\n`;
    }

    // Update identity with stack fingerprint
    const identityRe = /## Identity\n[\s\S]*?(?=\n## )/;
    if (identityRe.test(content)) {
      content = content.replace(identityRe, `## Identity\n${fingerprint}\n\n`);
    }

    fs.writeFileSync(targetFile, content, 'utf8');
    console.log(`  Updated: ${targetFile}`);
  } else {
    const rulesMarkdown = formatDiscoveredRules(rules);
    const content = `---
intent: general
description: ${fingerprint}
budget:
  identity: 10
  route_context: 35
  working_memory: 15
  traces: 10
  reserved: 30
---

## Identity
${fingerprint}

## Route Context
${rulesMarkdown}

### Skip
(none yet — rules will be demoted here by auto-governance if unused)

## Working Memory
- .harness/sessions/{current}/state.md
- .harness/memory/work-status.md (Active Work section)

## Trace Insights
- Query: last 5 sessions
`;
    fs.writeFileSync(targetFile, content, 'utf8');
    console.log(`  Created: ${targetFile}`);
  }

  const layerLabel = personal ? 'personal (gitignored)' : 'repo (committable to git)';
  console.log(`  Layer: ${layerLabel}`);
  console.log(`  Rules written: ${rules.length}`);
  console.log('');
}
